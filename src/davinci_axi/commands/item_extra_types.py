"""Write and read Protocols for the item edit extras (U25, KTD5).

They cover the calls `resolve_types_edit` does not declare, so the item modules share one cast
target.
"""

from __future__ import annotations

from typing import Any, Protocol

from davinci_axi.resolve_types import Info, TimelineItemApi
from davinci_axi.resolve_types_edit import TimelineEdit, TimelineItemEdit


class ItemExtra(TimelineItemEdit, Protocol):
    def AddTransition(self, transitionOptions: Info) -> TimelineItemApi | None: ...
    def UpdateSidecar(self) -> bool: ...
    def AddTake(
        self, mediaPoolItem: Any, startFrame: int | None = None, endFrame: int | None = None
    ) -> bool: ...
    def DeleteTakeByIndex(self, idx: int) -> bool: ...
    def SelectTakeByIndex(self, idx: int) -> bool: ...
    def FinalizeTake(self) -> bool: ...
    def SetOutputBlanking(self, outputBlanking: Info) -> bool: ...
    def SetUseTimelineForOutputBlanking(self, useTimelineOutputBlanking: bool) -> bool: ...
    def GetStereoLeftFloatingWindowParams(self) -> dict[int, Info]: ...
    def GetStereoRightFloatingWindowParams(self) -> dict[int, Info]: ...
    def GetMarkerByCustomData(self, customData: str) -> Info: ...
    def UpdateMarkerCustomData(self, frameId: int, customData: str) -> bool: ...


class TimelineLink(TimelineEdit, Protocol):
    def SetClipsLinked(self, timelineItems: list[Any], linked: bool) -> bool: ...
