"""Typed boundary for the Resolve scripting API (KTD5): phase-1 methods only.

The real objects are opaque proxies; `connect` casts them to these protocols. A unit that needs
more methods declares its own `class TimelineEdit(TimelineApi, Protocol)` in its own module.
Return values from Resolve are untyped dicts, so they use `Any` for the values.
"""

from __future__ import annotations

from typing import Any, Protocol

Info = dict[str, Any]


class MediaPoolItemApi(Protocol):
    def GetName(self) -> str: ...
    def GetMetadata(self, metadataType: str | None = None) -> Any: ...
    def GetThirdPartyMetadata(self, metadataType: str | None = None) -> Any: ...
    def GetMediaId(self) -> str: ...
    def GetUniqueId(self) -> str: ...
    def GetMarkers(self) -> dict[int, Info]: ...
    def GetFlagList(self) -> list[str]: ...
    def GetClipColor(self) -> str: ...
    def GetClipProperty(self, propertyName: str | None = None) -> Any: ...
    def GetAudioMapping(self) -> str: ...
    def GetMarkInOut(self) -> Info: ...
    def GetTimeline(self) -> TimelineApi | None: ...


class FolderApi(Protocol):
    def GetName(self) -> str: ...
    def GetSubFolderList(self) -> list[FolderApi]: ...
    def GetClipList(self) -> list[MediaPoolItemApi]: ...
    def GetIsFolderStale(self) -> bool: ...
    def GetUniqueId(self) -> str: ...


class MediaPoolApi(Protocol):
    def GetCurrentFolder(self) -> FolderApi: ...
    def GetRootFolder(self) -> FolderApi: ...
    def GetUniqueId(self) -> str: ...
    def GetSelectedClips(self) -> list[MediaPoolItemApi]: ...
    def GetClipMatteList(self, mediaPoolItem: MediaPoolItemApi) -> list[str]: ...


class TimelineItemApi(Protocol):
    def GetType(self) -> str: ...
    def GetName(self) -> str: ...
    def GetUniqueId(self) -> str: ...
    def GetStart(self, subframePrecision: bool = False) -> float: ...
    def GetEnd(self, subframePrecision: bool = False) -> float: ...
    def GetDuration(self, subframePrecision: bool = False) -> float: ...
    def GetLeftOffset(self, subframePrecision: bool = False) -> float: ...
    def GetRightOffset(self, subframePrecision: bool = False) -> float: ...
    def GetSourceStartFrame(self) -> int: ...
    def GetSourceEndFrame(self) -> int: ...
    def GetSourceStartTime(self) -> float: ...
    def GetSourceEndTime(self) -> float: ...
    def GetMediaPoolItem(self) -> MediaPoolItemApi | None: ...
    def GetMarkers(self) -> dict[int, Info]: ...
    def GetMarkerCustomData(self, frameId: int) -> str: ...
    def GetProperties(self) -> Info: ...
    def GetSpeed(self) -> Info: ...
    def GetFlagList(self) -> list[str]: ...
    def GetClipColor(self) -> str: ...
    def GetClipEnabled(self) -> bool: ...
    def GetCurrentVersion(self) -> Info: ...
    def GetVersionNameList(self, versionType: int) -> list[str]: ...
    def GetLinkedItems(self) -> list[TimelineItemApi]: ...
    def GetTrackTypeAndIndex(self) -> list[Any]: ...
    def GetSelectedTakeIndex(self) -> int: ...
    def GetTakesCount(self) -> int | None: ...
    def GetTakeByIndex(self, idx: int) -> Info | None: ...
    def GetFades(self) -> Info: ...
    def GetFusionCompCount(self) -> int: ...
    def GetFusionCompNameList(self) -> list[str]: ...
    def GetColorGroup(self) -> Any: ...
    def GetSourceAudioChannelMapping(self) -> str: ...
    def GetIsColorOutputCacheEnabled(self) -> bool: ...
    def GetVoiceIsolationState(self) -> Info: ...
    def GetOutputBlanking(self) -> Info: ...
    def GetUseTimelineForOutputBlanking(self) -> bool: ...
    def GetStereoConvergenceValues(self) -> dict[int, float]: ...


class TimelineApi(Protocol):
    def GetName(self) -> str: ...
    def GetUniqueId(self) -> str: ...
    def GetStartFrame(self) -> int: ...
    def GetEndFrame(self) -> int: ...
    def GetStartTimecode(self) -> str: ...
    def GetCurrentTimecode(self) -> str: ...
    def GetTrackCount(self, trackType: str) -> int: ...
    def GetItemListInTrack(self, trackType: str, index: int) -> list[TimelineItemApi]: ...
    def GetSelectedClips(self) -> list[TimelineItemApi]: ...
    def GetCurrentVideoItem(self) -> TimelineItemApi | None: ...
    def GetMarkers(self) -> dict[int, Info]: ...
    def GetMarkerCustomData(self, frameId: int) -> str: ...
    def GetTrackName(self, trackType: str, trackIndex: int) -> str: ...
    def GetTrackSubType(self, trackType: str, trackIndex: int) -> str: ...
    def GetIsTrackEnabled(self, trackType: str, trackIndex: int) -> bool: ...
    def GetIsTrackLocked(self, trackType: str, trackIndex: int) -> bool: ...
    def GetSettings(self) -> Info: ...
    def GetMediaPoolItem(self) -> MediaPoolItemApi | None: ...
    def GetMarkInOut(self) -> Info: ...
    def GetNormalizeAudioModes(self) -> list[str]: ...
    def GetOutputBlanking(self) -> Info: ...
    def Export(self, fileName: str, exportType: Any, exportSubtype: Any = None) -> bool: ...


class ProjectApi(Protocol):
    def GetName(self) -> str: ...
    def GetUniqueId(self) -> str: ...
    def GetMediaPool(self) -> MediaPoolApi: ...
    def GetCurrentTimeline(self) -> TimelineApi | None: ...
    def GetTimelineCount(self) -> int: ...
    def GetTimelineByIndex(self, idx: int) -> TimelineApi | None: ...
    def GetSettings(self) -> Info: ...
    def GetProjectSettingsPresetList(self) -> list[Info]: ...
    def GetRenderJobList(self) -> list[Info]: ...
    def GetRenderJobStatus(self, jobId: str) -> Info: ...
    def GetRenderPresetList(self) -> list[str]: ...
    def GetQuickExportRenderPresets(self) -> list[str]: ...
    def IsRenderingInProgress(self) -> bool: ...
    def GetRenderResolutions(
        self, format: str | None = None, codec: str | None = None
    ) -> list[Info]: ...
    def GetRenderFormats(self) -> Info: ...
    def GetAudioRenderFormats(self) -> Info: ...
    def GetRenderCodecs(self, renderFormatFileExtension: str) -> Info: ...
    def GetAudioRenderCodecs(self, audioRenderFormatFileExtension: str) -> Info: ...
    def GetCurrentRenderFormatAndCodec(self) -> dict[str, str]: ...
    def GetCurrentRenderMode(self) -> int: ...
    def GetColorGroupsList(self) -> list[Any]: ...


class ProjectManagerApi(Protocol):
    def GetCurrentProject(self) -> ProjectApi | None: ...
    def GetProjectListInCurrentFolder(self) -> list[str]: ...
    def GetFolderListInCurrentFolder(self) -> list[str]: ...
    def GetProjectLastModifiedTime(self, projectName: str) -> int: ...
    def GetProjectAttributesInCurrentFolder(self) -> dict[str, Info]: ...
    def GetCurrentFolder(self) -> str: ...
    def GetCurrentDatabase(self) -> Info: ...
    def GetDatabaseList(self) -> list[Info]: ...
    def ExportProject(
        self, projectName: str, filePath: str, withStillsAndLUTs: bool = True
    ) -> bool: ...


class ResolveApp(Protocol):
    def GetProjectManager(self) -> ProjectManagerApi: ...
    def GetCurrentProject(self) -> ProjectApi | None: ...
    def GetCurrentTimeline(self) -> TimelineApi | None: ...
    def GetMediaPool(self) -> MediaPoolApi | None: ...
    def GetCurrentPage(self) -> str: ...
    def GetVersion(self) -> list[Any]: ...
    def GetVersionString(self) -> str: ...
    def GetProductName(self) -> str: ...
    def IsStudio(self) -> bool: ...
    def GetLayoutPresetList(self) -> list[str]: ...
    def GetBurnInPresetList(self) -> list[str]: ...
    def GetKeyboardPresetList(self) -> list[str]: ...
    def GetCurrentKeyboardPreset(self) -> str: ...
    def GetKeyframeMode(self) -> int: ...
    def GetFairlightPresets(self) -> list[str]: ...
    def GetUserPreferencesPresetList(self) -> list[str]: ...
