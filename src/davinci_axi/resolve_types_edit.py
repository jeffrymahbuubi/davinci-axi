"""Write-method Protocols for the phase-2 mutations (KTD18).

One `<Class>Edit(<Class>Api, Protocol)` per Resolve class, covering every write call the
phase-2 commands make. Argument shapes follow docs/context/resolve-api-*.md and the `.pyi`:
list arguments are `list[Any]`, dict arguments are `Info`. A unit that needs a method missing
here declares a local Protocol in its own module (KTD5) and never edits this file.
"""

from __future__ import annotations

from typing import Any, Protocol

from davinci_axi.resolve_types import (
    FolderApi,
    Info,
    MediaPoolApi,
    MediaPoolItemApi,
    ProjectApi,
    ProjectManagerApi,
    ResolveApp,
    TimelineApi,
    TimelineItemApi,
)


class ResolveEdit(ResolveApp, Protocol):
    def OpenPage(self, pageName: str) -> bool: ...


class ProjectManagerEdit(ProjectManagerApi, Protocol):
    def LoadProject(self, projectName: str) -> ProjectApi | None: ...
    def CreateProject(
        self, projectName: str, mediaLocationPath: str | None = None
    ) -> ProjectApi | None: ...
    def DeleteProject(self, projectName: str) -> bool: ...
    def SaveProject(self) -> bool: ...
    def CreateFolder(self, folderName: str) -> bool: ...
    def GotoRootFolder(self) -> bool: ...
    def GotoParentFolder(self) -> bool: ...
    def OpenFolder(self, folderName: str) -> bool: ...
    def ImportProject(self, filePath: str, projectName: str | None = None) -> bool: ...
    def ArchiveProject(
        self,
        projectName: str,
        filePath: str,
        isArchiveSrcMedia: bool = True,
        isArchiveRenderCache: bool = True,
        isArchiveProxyMedia: bool = False,
    ) -> bool: ...
    def CloseProject(self, project: ProjectApi) -> bool: ...
    def DeleteFolder(self, folderName: str) -> bool: ...


class ProjectEdit(ProjectApi, Protocol):
    def SetCurrentTimeline(self, timeline: TimelineApi) -> bool: ...
    def SetName(self, projectName: str) -> bool: ...
    def SetSettings(self, settings: Info) -> bool: ...


class TimelineEdit(TimelineApi, Protocol):
    def SetName(self, timelineName: str) -> bool: ...
    def SetCurrentTimecode(self, timecode: str) -> bool: ...
    def SetStartTimecode(self, timecode: str) -> bool: ...
    def AddMarker(
        self,
        frameId: int,
        color: str,
        name: str,
        note: str,
        duration: int,
        customData: str | None = None,
    ) -> bool: ...
    def DeleteMarkersByColor(self, color: str) -> bool: ...
    def DeleteMarkerAtFrame(self, frameNum: int) -> bool: ...
    def DeleteMarkerByCustomData(self, customData: str) -> bool: ...
    def AddTrack(self, trackType: str, subTrackType: str | None = None) -> bool: ...
    def DeleteTrack(self, trackType: str, trackIndex: int) -> bool: ...
    def SetTrackEnable(self, trackType: str, trackIndex: int, enabled: bool) -> bool: ...
    def SetTrackLock(self, trackType: str, trackIndex: int, locked: bool) -> bool: ...
    def SetTrackName(self, trackType: str, trackIndex: int, name: str) -> bool: ...
    def DuplicateTimeline(self, timelineName: str) -> TimelineApi | None: ...
    def DeleteClips(self, timelineItems: list[Any], rippleDelete: bool = False) -> bool: ...
    def SetSettings(self, settings: Info) -> bool: ...


class TimelineItemEdit(TimelineItemApi, Protocol):
    def SetName(self, name: str) -> bool: ...
    def AddMarker(
        self,
        frameId: int,
        color: str,
        name: str,
        note: str,
        duration: int,
        customData: str | None = None,
    ) -> bool: ...
    def DeleteMarkersByColor(self, color: str) -> bool: ...
    def DeleteMarkerAtFrame(self, frameNum: int) -> bool: ...
    def DeleteMarkerByCustomData(self, customData: str) -> bool: ...
    def SetProperties(self, properties: Info) -> bool: ...
    def SetSpeed(self, speedOptions: Info) -> bool: ...
    def SetFades(self, fades: Info) -> bool: ...
    def AddFlag(self, color: str) -> bool: ...
    def ClearFlags(self, color: str) -> bool: ...
    def SetClipColor(self, colorName: str) -> bool: ...
    def ClearClipColor(self) -> bool: ...
    def SetClipEnabled(self, enabled: bool) -> bool: ...


class MediaPoolEdit(MediaPoolApi, Protocol):
    def AddSubFolder(self, folder: FolderApi, name: str) -> FolderApi | None: ...
    def SetCurrentFolder(self, folder: FolderApi) -> bool: ...
    def CreateEmptyTimeline(self, name: str) -> TimelineApi | None: ...
    def ImportTimelineFromFile(
        self, filePath: str, importOptions: Info | None = None
    ) -> TimelineApi | None: ...
    def DeleteTimelines(self, timelines: list[Any]) -> bool: ...
    def DeleteClips(self, clips: list[Any]) -> bool: ...
    def DeleteFolders(self, subfolders: list[Any]) -> bool: ...
    def MoveClips(self, clips: list[Any], targetFolder: FolderApi) -> bool: ...
    def MoveFolders(self, folders: list[Any], targetFolder: FolderApi) -> bool: ...
    def RelinkClips(self, clips: list[Any], folderPath: str) -> bool: ...
    def UnlinkClips(self, clips: list[Any]) -> bool: ...
    def ImportMedia(self, clipInfos: list[str] | list[Info]) -> list[MediaPoolItemApi]: ...


class MediaPoolItemEdit(MediaPoolItemApi, Protocol):
    def SetName(self, name: str) -> bool: ...
    def SetMetadata(self, metadata: Info) -> bool: ...
    def SetClipProperty(self, propertyName: str, propertyValue: str) -> bool: ...
    def AddMarker(
        self,
        frameId: int,
        color: str,
        name: str,
        note: str,
        duration: int,
        customData: str | None = None,
    ) -> bool: ...
    def DeleteMarkersByColor(self, color: str) -> bool: ...
    def DeleteMarkerAtFrame(self, frameNum: int) -> bool: ...
    def DeleteMarkerByCustomData(self, customData: str) -> bool: ...
    def AddFlag(self, color: str) -> bool: ...
    def ClearFlags(self, color: str) -> bool: ...
    def SetClipColor(self, colorName: str) -> bool: ...
    def ClearClipColor(self) -> bool: ...
    def LinkProxyMedia(self, proxyMediaFilePath: str) -> bool: ...
    def UnlinkProxyMedia(self) -> bool: ...
